#!/usr/bin/env python3
"""Hide apps listed in hypr/hidden-apps.txt from launchers on Hyprland only.

    python3 hypr/hide-apps.py           # write/remove overrides
    python3 hypr/hide-apps.py --check   # exit 1 if overrides are out of date (writes nothing)

For each ID it copies /usr/share/applications/<id>.desktop to ~/.local/share/applications/
with "Hyprland" added to NotShowIn=. Launchers compare that with $XDG_CURRENT_DESKTOP, so the
app disappears on Hyprland and still shows in KDE. The copy shadows the system file, so
re-run after package updates (install.sh does). Overrides this script made carry a marker
line; ones no longer listed are removed. Files without the marker are never touched.
"""
import os, pathlib, sys

REPO = pathlib.Path(__file__).resolve().parent
SYSTEM = [pathlib.Path(p) / "applications" for p in
          os.environ.get("XDG_DATA_DIRS", "/usr/local/share:/usr/share").split(":")]
USER = pathlib.Path.home() / ".local/share/applications"
MARK = "# generated by dotfiles/hypr/hide-apps.py; edit hypr/hidden-apps.txt instead\n"

ids = [l.split("#")[0].strip() for l in (REPO / "hidden-apps.txt").read_text().splitlines()]
ids = [i for i in ids if i]


def override(src):
    out, in_entry, done = [MARK], False, False
    for line in src.read_text().splitlines(keepends=True):
        if line.startswith("["):
            if in_entry and not done:  # leaving [Desktop Entry] without a NotShowIn= line
                out.append("NotShowIn=Hyprland;\n")
                done = True
            in_entry = line.strip() == "[Desktop Entry]"
        elif in_entry and line.startswith("NotShowIn="):
            vals = [v for v in line.strip()[len("NotShowIn="):].split(";") if v]
            line = "NotShowIn=" + ";".join(vals + ["Hyprland"] * ("Hyprland" not in vals)) + ";\n"
            done = True
        out.append(line)
    if in_entry and not done:
        out.append("NotShowIn=Hyprland;\n")
    return "".join(out)


want = {}
for i in ids:
    src = next((d / f"{i}.desktop" for d in SYSTEM if (d / f"{i}.desktop").exists()), None)
    if src is None:
        print(f"skip    {i}: not installed")
        continue
    want[USER / f"{i}.desktop"] = override(src)

check = "--check" in sys.argv
stale = []
for path, text in want.items():
    if path.exists() and not path.read_text().startswith(MARK):
        print(f"skip    {path.name}: you have your own override there, not touching it")
        continue
    if not path.exists() or path.read_text() != text:
        stale.append(f"write   {path}")
        if not check:
            USER.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
for path in USER.glob("*.desktop") if USER.exists() else []:
    if path not in want and path.read_text().startswith(MARK):
        stale.append(f"remove  {path}")
        if not check:
            path.unlink()

print(*stale, sep="\n") if stale else print("hidden apps up to date")
if check and stale:
    sys.exit(1)
