#!/usr/bin/env python3
"""The boot splash (Plymouth theme "none"): None's gray, and a row of squares in gruver16's vivid
colours (base08..base0F) that a slow wave runs through, each lighting up and lifting in turn.
Colours come from tty/colors.lua (generated from tty/themes/gruver16.yaml).

    plymouth.py DIR    write the theme into DIR (tty/boot.sh puts it in /usr/share/plymouth/themes/none)
"""
import pathlib, re, struct, sys, zlib

TTY = pathlib.Path(__file__).resolve().parents[1]
pal = dict(re.findall(r'(base0[0-9A-F]) = "([0-9a-f]{6})"', (TTY / "colors.lua").read_text()))
assert len(pal) == 16, "tty/colors.lua: expected base00..base0F"
VIVID = [pal[f"base0{c}"] for c in "89ABCDEF"]


def png(rgb):
    """a 1x1 png of one colour (Plymouth scales it to a square)"""
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    raw = b"\x00" + bytes.fromhex(rgb)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def floats(hexrgb):
    return ", ".join(f"{int(hexrgb[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4))


PLYMOUTH = """[Plymouth Theme]
Name=none
Description=None's gray with a gruver16 wave (dotfiles: tty/boot/plymouth.py)
ModuleName=script

[script]
ImageDir=/usr/share/plymouth/themes/none
ScriptFile=/usr/share/plymouth/themes/none/none.script
"""

SCRIPT = """# generated by tty/boot/plymouth.py from gruver16; do not edit
Window.SetBackgroundTopColor(%(bg)s);
Window.SetBackgroundBottomColor(%(bg)s);

count = %(count)d;
size = Math.Int(Window.GetHeight() / 90);    # 16px squares on 1440 lines
gap = Math.Int(size * 0.75);
lift = size * 0.6;
left = Window.GetX() + Window.GetWidth() / 2 - (count * size + (count - 1) * gap) / 2;
top = Window.GetY() + Window.GetHeight() / 2 - size / 2;

for (i = 0; i < count; i++) {
    block[i] = Sprite(Image("block" + i + ".png").Scale(size, size));
    block[i].SetX(left + i * (size + gap));
    block[i].SetY(top);
    block[i].SetOpacity(0.2);
}

# a wave runs left to right: each square brightens and rises, then settles back
t = 0;
fun refresh() {
    t++;
    for (i = 0; i < count; i++) {
        p = Math.Sin(t * 0.07 - i * 0.6);
        up = Math.Max(p, 0);
        block[i].SetOpacity(0.2 + 0.8 * up);
        block[i].SetY(top - lift * up);
    }
}
Plymouth.SetRefreshFunction(refresh);
"""


def main():
    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    (out / "none.plymouth").write_text(PLYMOUTH)
    (out / "none.script").write_text(SCRIPT % {"bg": floats(pal["base00"]), "count": len(VIVID)})
    for i, c in enumerate(VIVID):
        (out / f"block{i}.png").write_bytes(png(c))


if __name__ == "__main__":
    main()
